"""Generates src/serie/part3.ts and part4.ts (cut list, words table, caption pages) from the Parakeet transcripts + the edl*.json cut lists.
usage: serie_build.py <scratch dir holding words*.json and edl*.json>"""
import json, re, sys
W = sys.argv[1]
J = lambda n: json.load(open(W + n))
w2, w3, w4 = J('words2.json'), J('words3.json'), J('words4.json')
SHORT = lambda t: len(re.sub(r'[^\wÀ-ÿ%]', '', t)) <= 3
def paginate(items):
    pages = []; cur = []
    txt = lambda c: ' '.join(x[1] for x in c)
    for it in items:
        cur.append(it); t = it[1]
        if re.search(r'[.?!]$', t) or (t.endswith(',') and len(txt(cur)) >= 12) or len(txt(cur)) >= 21:
            pages.append(cur); cur = []
    if cur: pages.append(cur)
    for i, p in enumerate(pages):
        if len(p) > 1 and SHORT(p[-1][1]) and not re.search(r'[.?!,]$', p[-1][1]) and i + 1 < len(pages):
            pages[i + 1] = [p.pop()] + pages[i + 1]
    res = []
    for p in pages:
        if res and len(p) == 1 and len(txt(res[-1])) + len(p[0][1]) + 1 <= 26 and not re.search(r'[.?!]$', res[-1][-1][1]): res[-1] += p
        else: res.append(p)
    return res

def build(pid, const, files, pieces, note):
    """pieces: list of (edl json, file index, transcript, base key, word ranges, fixes, skips, highlights)"""
    segs = []; words = {}; pages = []
    for edl, f, wl, base, ranges, fix, skip, hl in pieces:
        cuts = J(edl)
        if pid == 'parte4' and edl == 'edl4_f4.json':
            # from "A gente vai fazer oito minutos com LED vermelho…" to the end of arquivo 04: keep everything, no cuts (b-roll + narration)
            cuts = [c for c in cuts if c[0] < 125] + [[130.93, 189.2]]
        for a, b in cuts:
            if f == 1 and pid == 'parte3' and abs(a - 0.15) < 0.01: a = 0.0      # arquivo 03 starts with speech
            segs.append([a, b, f])
        for a, b in ranges:
            items = []
            for k in range(a, b + 1):
                t = fix.get(k, wl[k]['w']); words[base + k] = dict(t=t, s=round(wl[k]['s'], 2), f=f, hl=k in hl, skip=k in skip)
                if k not in skip: items.append((base + k, t))
            for p in paginate(items): pages.append([p[0][0], p[-1][0]])
    out = [f'// Series {pid.upper()} — generated by tools/serie_build.py (Parakeet-TDT v3 + tools/serie_edl.py cut lists).', '// ' + note,
           'import type { SerieWord, SeriePart } from "./types";', '', f'export const {const}_WORDS: Record<number, SerieWord> = {{']
    for k in sorted(words):
        x = words[k]; out.append(f'  {k}: {{ t: {json.dumps(x["t"], ensure_ascii=False)}, s: {x["s"]:.2f}, f: {x["f"]}{", hl: true" if x["hl"] else ""}{", skip: true" if x["skip"] else ""} }},')
    out += ['};', f'export const {const}: SeriePart = {{', f'  id: "{pid}",', '  videoFiles: ' + json.dumps(files) + ',', '  segments: ' + json.dumps(segs) + ',', '  pages: ' + json.dumps(pages) + ',', '};']
    open(f'src/serie/{pid.replace("parte", "part")}.ts', 'w').write('\n'.join(out) + '\n')
    print(pid, len(words), 'words', len(pages), 'pages', round(sum(b - a for a, b, _ in segs), 1), 's of speech')

