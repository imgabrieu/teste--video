"""Builds src/risca/words.ts (caption words + pages) from the Parakeet transcript with hand corrections (cross-checked with Whisper-small)."""
import json, re
w = json.load(open('analysis/risca/words.parakeet.json'))
fix = {11: "alargar?", 17: "dermatologista,", 18: "seja", 19: "alopecia", 20: "androgenética,", 21: "vocês", 28: "alargando?", 35: "alopecia", 47: "padrão", 48: "androgênico,",
       50: "que", 51: "o", 66: "folículo.", 69: "alopecia", 75: "folículo piloso.", 77: "Então,", 81: "nesse", 84: "alopecia.", 96: "prognóstico", 114: "Passoni."}
skip = {27, 76, 115}
hl = {3, 14, 44, 45, 61, 63, 78, 80, 85, 86, 96, 114}
SHORT = lambda t: len(re.sub(r'[^\wÀ-ÿ%]', '', t)) <= 3
items = [(i, fix.get(i, x['w'])) for i, x in enumerate(w) if i not in skip]
txt = lambda c: ' '.join(t for _, t in c)
pages = []; cur = []
for it in items:
    cur.append(it); t = it[1]; ln = len(txt(cur))
    if re.search(r'[.?!]$', t) or (t.endswith(',') and ln >= 9) or ln >= 17 or len(cur) >= 4:
        pages.append(cur); cur = []
if cur: pages.append(cur)
for i, p in enumerate(pages):
    if len(p) > 1 and SHORT(p[-1][1]) and not re.search(r'[.?!,]$', p[-1][1]) and i + 1 < len(pages):
        pages[i + 1] = [p.pop()] + pages[i + 1]
res = []
for p in pages:
    if len(p) == 1 and res and len(res[-1]) >= 2 and not re.search(r'[.?!]$', p[0][1]) is False:
        p = [res[-1].pop()] + p
    res.append(p)
pages = [[p[0][0], p[-1][0]] for p in res if p]
pages = [[0, 3], [4, 7], [8, 9], [10, 11], [12, 14], [15, 17], [18, 20], [21, 24], [25, 28], [29, 30], [31, 33], [34, 36], [37, 39], [40, 42], [43, 45], [46, 48], [49, 53], [54, 57], [58, 60], [61, 63], [64, 64], [65, 66], [67, 69], [70, 70], [71, 73], [74, 75], [77, 80], [81, 84], [85, 88], [89, 92], [93, 96], [97, 99], [100, 103], [104, 106], [107, 108], [109, 112], [113, 114]]  # hand-made pages (meaning + breath)
out = ['// Risca video — caption words (SOURCE seconds) and pages. Parakeet-TDT v3 + hand corrections (Whisper-small cross-check). Generated by tools/risca_words.py',
       'export type RWord = { t: string; s: number; hl?: boolean };', 'export const RWORDS: Record<number, RWord> = {']
for i, x in enumerate(w):
    if i in skip: continue
    out.append(f'  {i}: {{ t: {json.dumps(fix.get(i, x["w"]), ensure_ascii=False)}, s: {round(x["s"], 2):.2f}{", hl: true" if i in hl else ""} }},')
out += ['};', 'export const RPAGES: [number, number][] = ' + json.dumps(pages) + ';']
open('src/risca/words.ts', 'w').write('\n'.join(out) + '\n')
words = dict(items)
print(len(pages), 'pages'); print(' | '.join(' '.join(words[k] for k in range(a, b + 1) if k in words) for a, b in pages))
