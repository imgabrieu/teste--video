"""Generates src/serie/part3.ts (words table, caption pages, cut list) from the Parakeet transcripts + edl3_*.json cut lists."""
import json, re, sys
W = sys.argv[1]
w2 = json.load(open(W + 'words2.json')); w3 = json.load(open(W + 'words3.json')); w4 = json.load(open(W + 'words4.json'))
hook = json.load(open(W + 'edl3_hook.json')); e3 = json.load(open(W + 'edl3_f3.json')); e4 = json.load(open(W + 'edl3_f4.json'))
e3[0][0] = 0.0                       # file 03 starts with speech
for s in e4:
    if abs(s[1] - 139.9) < 0.05: s[1] = 140.13   # cut inside the 0.1 s gap after "sanguínea,"
segs = [[a, b, 0] for a, b in hook] + [[a, b, 1] for a, b in e3] + [[a, b, 2] for a, b in e4]
src = {
    0: (w2, 20000, [(296, 305)], {}, set(), {302, 303}),
    1: (w3, 30000, [(0, 29), (30, 43), (50, 66), (109, 127), (134, 161), (211, 244), (331, 353), (388, 420)],
        {4: "micronizar", 24: "células-tronco,", 28: "exossomos", 29: "autólogos.", 30: "Após", 32: "micronização", 50: "Próximo ao", 211: "Agora", 388: "Cada"},
        {25}, {24, 28, 29, 53, 54, 141, 142, 161, 217, 338, 339, 398}),
    2: (w4, 40000, [(0, 24), (53, 88), (108, 126), (154, 188), (250, 268), (300, 337)],
        {61: "drug", 70: "couro", 125: "vasodilatação."}, {126}, {11, 83, 84, 167, 254, 255, 333, 334}),
}
SHORT = lambda t: len(re.sub(r'[^\wÀ-ÿ%]', '', t)) <= 3
def paginate(items):
    pages = []; cur = []
    txt = lambda c: ' '.join(x[1] for x in c)
    for it in items:
        cur.append(it); t = it[1]
        if re.search(r'[.?!]$', t) or (t.endswith(',') and len(txt(cur)) >= 12) or len(txt(cur)) >= 21:
            pages.append(cur); cur = []
    if cur: pages.append(cur)
    for i, p in enumerate(pages):
        if len(p) > 1 and SHORT(p[-1][1]) and not re.search(r'[.?!,]$', p[-1][1]) and i + 1 < len(pages):
            pages[i + 1] = [p.pop()] + pages[i + 1]
    res = []
    for p in pages:
        if res and len(p) == 1 and len(txt(res[-1])) + len(p[0][1]) + 1 <= 26 and not re.search(r'[.?!]$', res[-1][-1][1]): res[-1] += p
        else: res.append(p)
    return res
words = {}; pages = []
for f, (wl, base, ranges, fix, skip, hl) in src.items():
    for a, b in ranges:
        items = []
        for k in range(a, b + 1):
            t = fix.get(k, wl[k]['w']); words[base + k] = dict(t=t, s=round(wl[k]['s'], 2), f=f, hl=k in hl, skip=k in skip)
            if k not in skip: items.append((base + k, t))
        for p in paginate(items): pages.append([p[0][0], p[-1][0]])
out = ['// Series PART 3 — generated by tools/serie_build_part3.py: hook from arquivo 02 (keys 20000+), arquivo 03 (30000+), arquivo 04 (40000+). Parakeet-TDT v3 + tools/serie_edl.py.',
       '// Hand fixes: micronizar/micronização, células-tronco, exossomos autólogos, drug delivery, couro cabeludo, vasodilatação, "Após". Removed: repeated micronization explanation, garbled comfort/tubes passage, LED-vs-laser repetition, garbled protocol name.',
       'import type { SerieWord, SeriePart } from "./types";', '', 'export const PART3_WORDS: Record<number, SerieWord> = {']
for k in sorted(words):
    x = words[k]; out.append(f'  {k}: {{ t: {json.dumps(x["t"], ensure_ascii=False)}, s: {x["s"]:.2f}, f: {x["f"]}{", hl: true" if x["hl"] else ""}{", skip: true" if x["skip"] else ""} }},')
out += ['};', 'export const PART3: SeriePart = {', '  id: "parte3",', '  videoFiles: ["video/serie_v2.mp4", "video/serie_v3.mp4", "video/serie_v4.mp4"],', '  segments: ' + json.dumps(segs) + ',', '  pages: ' + json.dumps(pages) + ',', '};']
open('src/serie/part3.ts', 'w').write('\n'.join(out) + '\n')
print(len(words), len(pages), 'speech seconds', round(sum(b - a for a, b, _ in segs), 1))
